def shade(color, factor):
    return tuple(max(0, min(255, int(c * factor))) for c in color)


def palette_for(index):
    skin_key, hair_key, shirt, overalls, boots, hat, beard = PALETTES[index]
    skin = SKIN[skin_key]
    hair = HAIR[hair_key]
    colors = {
        "H": hair,
        "S": skin,
        "E": (48, 38, 34),
        "M": shade(skin, 0.72),
        "B": shade(hair, 1.05),
        "T": shirt,
        "V": overalls,
        "v": shade(overalls, 0.72),
        "K": boots,
        "k": shade(boots, 0.72),
        # Props are shared across variants: a rod is a rod whoever holds it.
        # The line is not baked in -- see fisherman.gd::_draw(). The outline
        # pass grows around a 1px line and turns it into a 3px blade, and
        # its length has to reach the water anyway, so it is drawn instead.
        "R": (120, 82, 50),
        "P": (228, 198, 138),
    }
    if hat is not None:
        colors["A"] = hat
        colors["a"] = shade(hat, 0.78)
    return colors, hat is not None, beard


def parse_map(text):
    """Turns a map literal into a list of exactly FRAME_H rows."""
    rows = [line for line in text.strip("\n").split("\n")]
    if len(rows) != FRAME_H:
        raise ValueError("map has %d rows, expected %d" % (len(rows), FRAME_H))
    for row in rows:
        if len(row) != FRAME_W:
            raise ValueError("row %r is %d wide, expected %d" % (row, len(row), FRAME_W))
    return rows


def draw_frame(rows, colors, has_hat, has_beard, direction):
    px = {}
    for y, row in enumerate(rows):
        for x, char in enumerate(row):
            if char != ".":
                px[(x, y)] = colors[char]

    if has_beard and direction in BEARDS:
        for y, row in BEARDS[direction]:
            for x, char in enumerate(row):
                if char != "." and (x, y) in px:
                    px[(x, y)] = colors["B"]

    if has_hat:
        for y, row in enumerate(parse_overlay(HATS[direction])):
            for x, char in enumerate(row):
                if char != ".":
                    px[(x, y)] = colors[char]

    _apply_edge_shading(px)
    _apply_outline(px)

    image = Image.new("RGBA", (FRAME_W, FRAME_H), (0, 0, 0, 0))
    for (x, y), color in px.items():
        image.putpixel((x, y), color + (255,))
    return image


def parse_overlay(text):
    return [line for line in text.strip("\n").split("\n")]


def _apply_edge_shading(px):
    """Darkens the bottom edge of each body mass for a bit of volume.

    Deliberately the bottom and not a side: the side-facing frames get
    mirrored at runtime for the opposite direction, and side shading
    would flip the implied light source along with them.
    """
    shaded = {}
    for (x, y), color in px.items():
        if (x, y + 1) not in px:
            shaded[(x, y)] = shade(color, 0.84)
    px.update(shaded)


def _apply_outline(px):
    """Grows a 1px dark outline out of the silhouette.

    The outline color is derived from the pixel it touches rather than a
    flat black, so hair, cloth and skin each keep their own hue at the
    edges instead of the whole sprite reading as a sticker.
    """
    outline = {}
    for (x, y) in list(px.keys()):
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if not (0 <= nx < FRAME_W and 0 <= ny < FRAME_H):
                continue
            if (nx, ny) in px:
                continue
            outline.setdefault((nx, ny), shade(px[(x, y)], 0.42))
    px.update(outline)


def build_sheet(index):
    colors, has_hat, has_beard = palette_for(index)
    sheet = Image.new("RGBA", (FRAME_W * COLS, FRAME_H * ROWS), (0, 0, 0, 0))
    for row, frames in enumerate(FRAMES):
        for col, frame_map in enumerate(frames):
            frame = draw_frame(parse_map(frame_map), colors, has_hat, has_beard, row)
            sheet.paste(frame, (col * FRAME_W, row * FRAME_H))
    return sheet


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--preview", action="store_true", help="also write a scaled contact sheet")
    args = parser.parse_args()

    os.makedirs(OUT_DIR, exist_ok=True)
    sheets = []
    for index in range(len(PALETTES)):
        sheet = build_sheet(index)
        path = os.path.join(OUT_DIR, "v%d.png" % index)
        sheet.save(path)
        sheets.append(sheet)
        print("wrote %s" % path)

    if args.preview:
        scale = 4
        gap = 8
        w = (sheets[0].width * scale + gap) * len(sheets) + gap
        h = sheets[0].height * scale + gap * 2
        contact = Image.new("RGBA", (w, h), (28, 34, 42, 255))
        for i, sheet in enumerate(sheets):
            big = sheet.resize((sheet.width * scale, sheet.height * scale), Image.NEAREST)
            contact.paste(big, (gap + i * (big.width + gap), gap), big)
        contact.save("sprite_preview.png")
        print("wrote sprite_preview.png")


if __name__ == "__main__":
    main()
