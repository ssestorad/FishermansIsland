"""Generates the fisherman sprite sheets from readable pixel maps.

Each appearance variant is baked into one 144x72 sheet laid out as a
9x3 grid of 16x24 frames:

    columns -> 0 = stand, 1 = walk A, 2 = walk B,
               3 = fish idle A, 4 = fish idle B, 5 = fish strike,
               6 = consume low, 7 = consume high, 8 = sit
    rows    -> 0 = facing down, 1 = facing right, 2 = facing up

Poses only exist for the direction they are actually used in: fishing is
always played facing right (fisherman.gd forces that on entering the
state, the water is east) and the need poses always face down. Every
other cell repeats that direction's stand frame, so an unexpected facing
degrades to standing rather than to a blank frame.

Sprite2D reads them directly via hframes/vframes/frame_coords, so the
game never slices or recolors anything at runtime.

Run from the repo root:

    python tools/generate_fisherman_sprites.py

Add --preview to also write a scaled-up contact sheet next to the
output for eyeballing the result.
"""

